#!/usr/bin/env python3
"""Emit candidate SBB result and source/spec AC equations from projection JSON."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys

ARTIFACTS = Path(r"C:\Users\Yuriy\Desktop\CircuitWeave-main\artifacts\8080").resolve()
SCHEMA = "hardwarebridge.intel8080.sbb-hwir/v1"
EXPECTED = {
    "result16": "(A - operand - CY_in) mod 65536",
    "result8": "result16[7:0]",
    "A_next": "result8",
    "CY_next": "result16 > 0x00FF (source helper; borrow on byte underflow)",
    "AC_source_next": "zero_extend_1(A[3:0]) + zero_extend_1((~operand)[3:0]) + 1 > 0xF (source omits CY_in)",
    "Z_next": "result8 == 0",
    "S_next": "result8[7]",
    "P_next": "even_parity8(result8); source verified against all 256 ParityTable entries",
    "PC_next": "PC + 1",
}
DISPATCH = [(f"0x{code:02X}", f"SBB {reg}") for code, reg in
            ((0x99, "C"), (0x9A, "D"), (0x9B, "E"), (0x9C, "H"), (0x9D, "L"), (0x9E, "M"), (0x9F, "A"))]
TRACE_SYMBOLS = {"SBB", "SBB_C", "SBB_D", "SBB_E", "SBB_H", "SBB_L", "SBB_M", "SBB_A",
                 "CalcSZPC", "CalcZeroFlag", "CalcSignFlag", "CalcCarryFlag", "CalcParityFlag",
                 "CalcAuxCarryFlag", "GetParity"}
SPEC_AC_FORMULA = "zero_extend_1(A[3:0]) + zero_extend_1((~operand)[3:0]) + (1 - CY_in) > 0xF"


def inside_artifacts(path: Path) -> bool:
    try:
        path.relative_to(ARTIFACTS)
        return True
    except ValueError:
        return False


def emit(projection_path: Path, output_dir: Path) -> None:
    projection_path = projection_path.resolve(strict=True)
    output_dir = output_dir.resolve()
    if not inside_artifacts(projection_path) or not inside_artifacts(output_dir):
        raise ValueError("input and output paths must remain under artifacts/8080")
    if output_dir.exists():
        raise FileExistsError(f"refusing existing output directory: {output_dir}")
    for parent in (projection_path.parent, *projection_path.parents):
        if parent.exists() and parent.is_symlink():
            raise ValueError(f"refusing linked input path: {parent}")
    data = json.loads(projection_path.read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise ValueError("unsupported SBB projection schema")
    equations = {row["Name"]: row["Formula"] for row in data.get("equations", [])}
    if equations != EXPECTED:
        raise ValueError("SBB source equation set/formulas differ from reviewed projection")
    if data.get("architectureSelection", {}).get("auxCarryName") != "AC_spec_next" or \
            data["architectureSelection"].get("formula") != SPEC_AC_FORMULA:
        raise ValueError("Intel-spec SBB AC decision missing or changed")
    dispatch = [(row["opcode"], row["mnemonic"]) for row in data.get("dispatch", [])]
    if dispatch != DISPATCH:
        raise ValueError("SBB opcode dispatch mapping changed")
    sources = []
    for row in data.get("sourceTrace", []):
        source = Path(row["file"]).resolve(strict=True)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if digest != row["sha256"]:
            raise ValueError(f"source hash changed after Roslyn projection: {source}")
        sources.append({"symbol": row["symbol"], "file": str(source), "sha256": digest,
                        "startLine": row["startLine"], "endLine": row["endLine"]})
    if {row["symbol"] for row in sources} != TRACE_SYMBOLS:
        raise ValueError("incomplete SBB source dependency trace")

    source_comment = "\n".join(
        f"// source {row['symbol']}: {row['file']}:{row['startLine']}-{row['endLine']} sha256={row['sha256']}"
        for row in sources
    )
    sv = f'''// Candidate-only manual-schema emission from {SCHEMA}.
// Not generated by CircuitWeave; scalar MLIR below covers result16 only.
{source_comment}
// Source dispatch: 99h-9Fh except 98h; RTL also supports the architectural SBB B form.
// AC_source_next preserves the emulator helper; AC_spec_next is the Intel-selected RTL behavior.
module intel8080_sbb_source_projected (
    input logic [7:0] A,
    input logic [7:0] operand,
    input logic CY_in,
    input logic [15:0] PC,
    output logic [15:0] result16,
    output logic [7:0] result8,
    output logic [7:0] A_next,
    output logic sign_next,
    output logic zero_next,
    output logic parity_next,
    output logic carry_next,
    output logic aux_carry_source_next,
    output logic aux_carry_spec_next,
    output logic [15:0] PC_next
);
    logic [4:0] source_nibble_sum;
    logic [4:0] spec_nibble_sum;
    always_comb begin
        result16 = {{8'h00, A}} - {{8'h00, operand}} - {{{{15{{1'b0}}}}, CY_in}};
        result8 = result16[7:0];
        A_next = result8;
        sign_next = result8[7];
        zero_next = (result8 == 8'h00);
        parity_next = ~^result8;
        carry_next = (result16 > 16'h00FF);
        source_nibble_sum = {{1'b0, A[3:0]}} + {{1'b0, (~operand[3:0])}} + 5'd1;
        spec_nibble_sum = {{1'b0, A[3:0]}} + {{1'b0, (~operand[3:0])}} + (CY_in ? 5'd0 : 5'd1);
        aux_carry_source_next = source_nibble_sum[4];
        aux_carry_spec_next = spec_nibble_sum[4];
        PC_next = PC + 16'd1;
    end
endmodule
'''
    tb = r'''`timescale 1ns/1ps
module tb_sbb_source_projected;
    logic [7:0] A, operand;
    logic CY_in;
    logic [15:0] PC;
    logic [15:0] result16, PC_next;
    logic [7:0] result8, A_next;
    logic sign_next, zero_next, parity_next, carry_next;
    logic aux_carry_source_next, aux_carry_spec_next;
    integer vector, a_value, b_value, borrow_value, difference, wrapped;
    integer source_nibble, spec_nibble, bit_index, ones;
    intel8080_sbb_source_projected dut(.*);
    initial begin
        for (vector = 0; vector < 131072; vector = vector + 1) begin
            borrow_value = vector & 1;
            b_value = (vector >> 1) & 255;
            a_value = (vector >> 9) & 255;
            A = a_value[7:0]; operand = b_value[7:0]; CY_in = borrow_value[0]; PC = vector[15:0];
            #1;
            difference = a_value - b_value - borrow_value;
            wrapped = difference & 65535;
            source_nibble = (a_value & 15) + ((~b_value) & 15) + 1;
            spec_nibble = (a_value & 15) + ((~b_value) & 15) + (1 - borrow_value);
            ones = 0;
            for (bit_index = 0; bit_index < 8; bit_index = bit_index + 1)
                ones = ones + ((wrapped >> bit_index) & 1);
            if (result16 !== wrapped[15:0] || result8 !== wrapped[7:0] || A_next !== wrapped[7:0] ||
                sign_next !== wrapped[7] || zero_next !== (wrapped[7:0] == 0) ||
                parity_next !== ((ones % 2) == 0) || carry_next !== (wrapped > 255) ||
                aux_carry_source_next !== (source_nibble > 15) ||
                aux_carry_spec_next !== (spec_nibble > 15) || PC_next !== ((vector + 1) & 16'hffff))
                $fatal(1, "SBB projection mismatch vector=%05h A=%02h operand=%02h CY=%0d result=%04h", vector, A, operand, CY_in, result16);
        end
        $display("PASS source/spec SBB RTL: 131072 A/operand/CY vectors; source AC and spec AC checked separately; full PC domain");
        $finish;
    end
endmodule
'''
    output_dir.mkdir(parents=True, exist_ok=False)
    (output_dir / "intel8080_sbb_source_projected.sv").write_text(sv, encoding="utf-8")
    (output_dir / "tb_sbb_source_projected.sv").write_text(tb, encoding="utf-8")
    manifest = {
        "schema": "hardwarebridge.intel8080.sbb-sv-candidate/v1",
        "status": "candidate-only manual schema emitter; not CircuitWeave SystemVerilog output",
        "sourceProjection": str(projection_path),
        "sourceProjectionSha256": hashlib.sha256(projection_path.read_bytes()).hexdigest(),
        "sourceTrace": sources,
        "dispatch": dispatch,
        "sourceEquations": EXPECTED,
        "architectureSelection": data["architectureSelection"],
        "validationScope": "Icarus checks all 131072 A/operand/CY_in vectors and all 65536 PC increment values; checks both source AC and Intel-selected AC",
        "notIncluded": ["opcode decode", "CPU register storage", "memory timing", "clock/reset", "instruction timing"]
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Created candidate SBB SV and exhaustive testbench under {output_dir}")


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: emit_sbb_projection_sv.py <absolute-projection.json> <new-output-directory>", file=sys.stderr)
        return 2
    try:
        emit(Path(sys.argv[1]), Path(sys.argv[2]))
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
