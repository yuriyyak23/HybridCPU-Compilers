#!/usr/bin/env python3
"""Emit the bounded multi-output ADD combinational slice from source-checked HWIR JSON.

This is a small manual-schema emitter, not CircuitWeave's RTL backend. CircuitWeave's
current scalar emitter supports one output; this module contains the source helper's
result and flag equations and therefore stays explicitly candidate-only.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys


ARTIFACTS = Path(r"C:\Users\Yuriy\Desktop\CircuitWeave-main\artifacts\8080").resolve()
SCHEMA = "hardwarebridge.intel8080.add-hwir/v1"
EXPECTED = {
    "sum9": "zero_extend_1(A) + zero_extend_1(operand)",
    "result8": "sum9[7:0]",
    "A_next": "result8",
    "CY_next": "sum9[8] (source helper: ushort value > 0xFF)",
    "AC_next": "zero_extend_1(A[3:0]) + zero_extend_1(operand[3:0]) > 0xF",
    "Z_next": "result8 == 0",
    "S_next": "result8[7]",
    "P_next": "even_parity8(result8); source verified against all 256 ParityTable entries",
    "PC_next": "PC + 1",
}
DISPATCH = [("0x80", "ADD B"), ("0x81", "ADD C"), ("0x82", "ADD D"), ("0x87", "ADD A")]


def inside_artifacts(path: Path) -> bool:
    try:
        path.relative_to(ARTIFACTS)
        return True
    except ValueError:
        return False


def emit(projection_path: Path, output_dir: Path) -> None:
    projection_path = projection_path.resolve(strict=True)
    output_dir = output_dir.resolve()
    if not inside_artifacts(projection_path) or not inside_artifacts(output_dir):
        raise ValueError("input and output paths must remain under artifacts/8080")
    if output_dir.exists():
        raise FileExistsError(f"refusing existing output directory: {output_dir}")
    for parent in (projection_path.parent, *projection_path.parents):
        if parent.exists() and parent.is_symlink():
            raise ValueError(f"refusing linked input path: {parent}")
    data = json.loads(projection_path.read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise ValueError("unsupported ADD projection schema")
    equations = {row["Name"]: row["Formula"] for row in data.get("equations", [])}
    if equations != EXPECTED:
        raise ValueError("ADD equation set/formulas differ from the reviewed source projection")
    dispatch = [(row["opcode"], row["mnemonic"]) for row in data.get("dispatch", [])]
    if dispatch != DISPATCH:
        raise ValueError("ADD opcode dispatch mapping changed")
    sources = []
    for row in data.get("sourceTrace", []):
        source = Path(row["file"]).resolve(strict=True)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if digest != row["sha256"]:
            raise ValueError(f"source hash changed after Roslyn projection: {source}")
        sources.append({"symbol": row["symbol"], "file": str(source), "sha256": digest,
                        "startLine": row["startLine"], "endLine": row["endLine"]})
    if {row["symbol"] for row in sources} != {"ADD", "CalcSZPC", "CalcZeroFlag", "CalcSignFlag",
                                             "CalcCarryFlag", "CalcParityFlag", "CalcAuxCarryFlag", "GetParity"}:
        raise ValueError("incomplete ADD source dependency trace")

    source_comment = "\n".join(
        f"// source {row['symbol']}: {row['file']}:{row['startLine']}-{row['endLine']} sha256={row['sha256']}"
        for row in sources
    )
    sv = f'''// Candidate-only manual-schema emission from {SCHEMA}.
// Not generated by CircuitWeave; the current scalar CircuitWeave backend admits one output.
{source_comment}
// Dispatch represented by this shared data-path slice: 80h ADD B, 81h ADD C, 82h ADD D, 87h ADD A.
module intel8080_add_source_projected (
    input  logic [7:0] A,
    input  logic [7:0] operand,
    input  logic [15:0] PC,
    output logic [8:0] sum9,
    output logic [7:0] result8,
    output logic [7:0] A_next,
    output logic sign_next,
    output logic zero_next,
    output logic parity_next,
    output logic carry_next,
    output logic aux_carry_next,
    output logic [15:0] PC_next
);
    logic [4:0] nibble_sum;
    always_comb begin
        sum9 = {{1'b0, A}} + {{1'b0, operand}};
        result8 = sum9[7:0];
        A_next = result8;
        sign_next = result8[7];
        zero_next = (result8 == 8'h00);
        parity_next = ~^result8;
        carry_next = sum9[8];
        nibble_sum = {{1'b0, A[3:0]}} + {{1'b0, operand[3:0]}};
        aux_carry_next = nibble_sum[4];
        PC_next = PC + 16'd1;
    end
endmodule
'''

    tb = r'''`timescale 1ns/1ps
module tb_add_source_projected;
    logic [7:0] A, operand;
    logic [15:0] PC;
    logic [8:0] sum9;
    logic [7:0] result8, A_next;
    logic sign_next, zero_next, parity_next, carry_next, aux_carry_next;
    logic [15:0] PC_next;
    integer vector, a_value, b_value, total, nibble_total, bit_index, ones;
    intel8080_add_source_projected dut(.*);
    initial begin
        for (vector = 0; vector < 65536; vector = vector + 1) begin
            a_value = (vector >> 8) & 255;
            b_value = vector & 255;
            A = a_value[7:0]; operand = b_value[7:0]; PC = vector[15:0];
            #1;
            total = a_value + b_value;
            nibble_total = (a_value & 15) + (b_value & 15);
            ones = 0;
            for (bit_index = 0; bit_index < 8; bit_index = bit_index + 1)
                ones = ones + ((total >> bit_index) & 1);
            if (sum9 !== total[8:0] || result8 !== total[7:0] || A_next !== total[7:0] ||
                sign_next !== total[7] || zero_next !== (total[7:0] == 0) ||
                parity_next !== ((ones % 2) == 0) || carry_next !== ((total >> 8) & 1) ||
                aux_carry_next !== (nibble_total > 15) || PC_next !== ((vector + 1) & 16'hffff))
                $fatal(1, "ADD projection mismatch vector=%04h A=%02h operand=%02h sum=%03h", vector, A, operand, sum9);
        end
        $display("PASS source-projected ADD RTL: 65536 operand pairs and 65536 PC increment values");
        $finish;
    end
endmodule
'''
    output_dir.mkdir(parents=True, exist_ok=False)
    (output_dir / "intel8080_add_source_projected.sv").write_text(sv, encoding="utf-8")
    (output_dir / "tb_add_source_projected.sv").write_text(tb, encoding="utf-8")
    manifest = {
        "schema": "hardwarebridge.intel8080.add-sv-candidate/v1",
        "status": "candidate-only manual schema emitter; not CircuitWeave SystemVerilog output",
        "sourceProjection": str(projection_path),
        "sourceProjectionSha256": hashlib.sha256(projection_path.read_bytes()).hexdigest(),
        "sourceTrace": sources,
        "dispatch": dispatch,
        "equations": EXPECTED,
        "validationScope": "Icarus testbench checks all 65,536 A/operand pairs and all 65,536 PC values",
        "notIncluded": ["opcode decode", "CPU register storage", "memory", "clock/reset", "instruction timing"]
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Created candidate ADD SV and exhaustive testbench under {output_dir}")


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: emit_add_projection_sv.py <absolute-projection.json> <new-output-directory>", file=sys.stderr)
        return 2
    try:
        emit(Path(sys.argv[1]), Path(sys.argv[2]))
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
